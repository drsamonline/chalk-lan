#!/usr/bin/env python3
"""Build the single-file board: one HTML file with everything inlined.

A teacher should be able to email the whiteboard. This takes docs/play/index.html
and folds web-kit, lan-kit, the engine and the QR encoder into it, so the result
runs from a memory stick or an attachment with no server, no folder and no
network. The service worker and the manifest are dropped — a single file has no
scope to register either.

    python3 scripts/bundle.py            # writes docs/play/chalk-single.html
    python3 scripts/bundle.py --check    # fails if the committed file is stale
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLAY = os.path.join(ROOT, "docs", "play")
SOURCE = os.path.join(PLAY, "index.html")
OUT = os.path.join(PLAY, "chalk-single.html")

BANNER = """<!--
  Chalk — the whole board in one file. Generated by scripts/bundle.py; do not edit.
  web-kit, lan-kit, the engine and the QR encoder are inlined below, so this file
  runs from file:// with no server, no folder and no network.
-->
"""


def build():
    with open(SOURCE, encoding="utf-8") as fh:
        html = fh.read()

    # drop the PWA wiring: a single file has no scope to register a worker
    html = re.sub(r'\s*<link rel="manifest"[^>]*>', "", html)

    def inline(match):
        src = match.group(1)
        path = os.path.join(PLAY, src)
        if not os.path.exists(path):
            raise SystemExit("missing script: %s" % src)
        with open(path, encoding="utf-8") as fh:
            body = fh.read()
        return "<script>\n/* ---- %s ---- */\n%s\n</script>" % (src, body)

    html, count = re.subn(r'<script src="([^"]+)"></script>', inline, html)
    if count < 4:
        raise SystemExit("expected four external scripts, inlined %d" % count)

    html = html.replace("<!doctype html>\n", "<!doctype html>\n" + BANNER, 1)
    return html


def main():
    html = build()
    if "--check" in sys.argv:
        if not os.path.exists(OUT):
            raise SystemExit("chalk-single.html is missing — run scripts/bundle.py")
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() != html:
                raise SystemExit("chalk-single.html is stale — run scripts/bundle.py")
        print("chalk-single.html is up to date (%d bytes)" % len(html))
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(html)
    print("wrote docs/play/chalk-single.html (%d bytes, sha %s)" %
          (len(html), hashlib.sha256(html.encode()).hexdigest()[:10]))


if __name__ == "__main__":
    main()
